// Real UI, isolated repositories, no account or model requests.
import { expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rename, cp } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createService } from '../server.mjs';
import { localDay } from '../workspace.mjs';
import { launchBrowser } from './browser.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
await mkdir(path.join(root, '.cache'), { recursive: true });
const fixture = await mkdtemp(path.join(root, '.cache/workspace-roots-ui-'));
const hub = path.join(fixture, 'hub');
async function project(folder, title, workspaceId) {
  await mkdir(path.join(folder, 'workspace/notes'), { recursive: true });
  await mkdir(path.join(folder, 'workspace/_shared'));
  const card = { id: 'notes', title, description: 'Repository-owned project notes', category: 'project', type: 'group', folder: 'notes', status: 'active', pinned: true, created: localDay(), defaultStep: 0, icon: 'preview.svg', steps: [{ name: 'Notes', path: 'notes.md' }, { name: 'Reader', path: 'index.html' }] };
  await writeFile(path.join(folder, 'workspace/workspace.json'), JSON.stringify({ workspaceId, title, entities: [card] }));
  await writeFile(path.join(folder, 'workspace/notes/notes.md'), `# ${title}\n\n![Project preview](preview.svg)`);
  await writeFile(path.join(folder, 'workspace/notes/preview.svg'), '<svg xmlns="http://www.w3.org/2000/svg" width="100" height="60"><rect width="100" height="60" fill="pink"/></svg>');
  await writeFile(path.join(folder, 'workspace/_shared/report.css'), 'body{background:#fff;color:#222;padding:30px} h1{color:rgb(255,0,0)} img{width:100px}');
  await writeFile(path.join(folder, 'workspace/notes/index.html'), `<html><head><link rel="stylesheet" href="../_shared/report.css"></head><body><h1>${title}</h1><img alt="Reader preview" src="preview.svg"></body></html>`);
  return { workspaceId, label: title, path: folder };
}
await project(hub, 'Personal notes');
const first = await project(path.join(fixture, 'first project'), 'First game', randomUUID());
const second = await project(path.join(fixture, 'second'), 'Second game', randomUUID());
await mkdir(path.join(hub, '.mrmak'));
await writeFile(path.join(hub, '.mrmak/workspace-roots.json'), JSON.stringify([first, second]));
await cp(path.join(root, 'public/assets'), path.join(root, 'dist/assets'), { recursive: true });
const service = await createService({ repo: hub, uiDir: path.join(root, 'dist') });
let browser;
try {
  browser = await launchBrowser();
  const page = await browser.newPage({ viewport: { width: 1200, height: 850 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(service.urls.workspace);
  const firstId = `${first.workspaceId}:notes`, secondId = `${second.workspaceId}:notes`;
  const card = id => page.locator(`.home [data-card="${id}"]`);
  await expect(card('notes')).toBeVisible();
  await expect(card(firstId)).toBeVisible(); await expect(card(secondId)).toBeVisible();
  assert.notEqual(await card(firstId).getByRole('link').getAttribute('href'), await card(secondId).getByRole('link').getAttribute('href'));
  await page.screenshot({ path: path.join(fixture, 'multiple-workspaces.png') });
  await card(firstId).getByRole('link').click();
  await expect(page.locator('.markdown-reader').getByRole('heading', { name: 'First game' })).toBeVisible();
  await expect(page.getByRole('img', { name: 'Project preview' })).toBeVisible();
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByRole('textbox', { name: 'Edit notes.md' }).fill('# Edited first game\n\nSaved in its own repository.');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.locator('.document-status')).toHaveText('Saved');
  assert.match(await readFile(path.join(first.path, 'workspace/notes/notes.md'), 'utf8'), /Edited first game/);
  assert.match(await readFile(path.join(second.path, 'workspace/notes/notes.md'), 'utf8'), /Second game/);
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  await page.getByRole('tab', { name: 'Reader', exact: true }).click();
  const reader = page.frameLocator('iframe.report-frame');
  await expect(reader.getByRole('heading', { name: 'First game' })).toBeVisible();
  await expect(reader.getByRole('heading', { name: 'First game' })).toHaveCSS('color', 'rgb(255, 0, 0)');
  await expect(reader.getByRole('img', { name: 'Reader preview' })).toBeVisible();
  await page.screenshot({ path: path.join(fixture, 'external-reader.png') });
  await page.locator('.topbar').getByRole('button', { name: /^Edit First game:/ }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Done', exact: true }).click();
  await expect(page.locator('.topbar').getByRole('button', { name: 'Edit First game: Done' })).toBeVisible();
  assert.equal(JSON.parse(await readFile(path.join(first.path, 'workspace/workspace.json'), 'utf8')).entities[0].status, 'done');
  await rename(first.path, first.path + '-missing');
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(page.locator('.home').getByText('Unavailable', { exact: true })).toBeVisible();
  await expect(card(secondId)).toBeVisible();
  await page.locator('.home').getByRole('link').filter({ hasText: 'Unavailable' }).click();
  await expect(page.getByRole('status')).toContainText('First game is unavailable');
  await page.screenshot({ path: path.join(fixture, 'missing-workspace.png') });
  await rename(first.path + '-missing', first.path);
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(card(firstId)).toBeVisible();
  await expect(page.locator('.home').getByText('Unavailable', { exact: true })).toHaveCount(0);
  assert.deepEqual(errors, []);
  console.log(`External workspace UI passed: duplicate IDs, local/external cards, Markdown edits, relative images/CSS, report navigation, metadata writes and missing-folder recovery. Screenshots: ${fixture}`);
} finally { await browser?.close(); await service.close(); }
